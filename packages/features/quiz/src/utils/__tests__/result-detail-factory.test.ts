import { describe, expect, it } from "vitest";
import {
  createPartner,
  createResourceLink,
  createResultDetail,
  LEARNING_STRATEGIES,
} from "../result-detail-factory";

describe("createPartner", () => {
  it("returns an object with roleId, brief, and descriptionContext", () => {
    const partner = createPartner("explorer", "a brief", "some context");
    expect(partner).toEqual({
      roleId: "explorer",
      brief: "a brief",
      descriptionContext: "some context",
    });
  });
});

describe("createResourceLink", () => {
  it("returns an object with text and link", () => {
    const link = createResourceLink("Read more", "https://example.com");
    expect(link).toEqual({
      text: "Read more",
      link: "https://example.com",
    });
  });
});

describe("createResultDetail", () => {
  const baseConfig = {
    id: "test-id",
    tags: ["tag1", "tag2"],
    slogan: "Test slogan",
    characteristics: "Test characteristics",
    scenery: "Test scenery",
    strategies: ["strategy1"],
    partners: [createPartner("explorer", "explorer brief", "explore context")],
    learningTraits: "Test learning traits",
    learningStrategies: [LEARNING_STRATEGIES.DEEP_READING],
    supportNeeded: ["support1"],
    islandDining: ["dish1"],
    islandDiningDescription: "Dining description",
    recommendedResources: "Resources text",
    recommendedResourceLinks: [createResourceLink("Link", "https://example.com")],
  };

  it("returns an IResultDetail object with all fields", () => {
    const result = createResultDetail(baseConfig);
    expect(result.id).toBe("test-id");
    expect(result.tags).toEqual(["tag1", "tag2"]);
    expect(result.slogan).toBe("Test slogan");
    expect(result.characteristics).toBe("Test characteristics");
    expect(result.scenery).toBe("Test scenery");
    expect(result.strategies).toEqual(["strategy1"]);
    expect(result.learningTraits).toBe("Test learning traits");
    expect(result.learningStrategies).toEqual([LEARNING_STRATEGIES.DEEP_READING]);
    expect(result.supportNeeded).toEqual(["support1"]);
    expect(result.islandDining).toEqual(["dish1"]);
    expect(result.islandDiningDescription).toBe("Dining description");
    expect(result.recommendedResources).toBe("Resources text");
    expect(result.recommendedResourceLinks).toEqual([
      { text: "Link", link: "https://example.com" },
    ]);
  });

  it("transforms partners using createPartnerDescription when roleId matches", () => {
    const result = createResultDetail(baseConfig);
    const partner = result.partners[0]!;
    // "explorer" is a known roleId in createPartnerDescription
    expect(partner.roleId).toBe("explorer");
    expect(partner.brief).toBe("explorer brief");
    // The description should be generated by the factory, not raw context
    expect(partner.description).toContain("explore context");
    expect(partner.description).not.toBe("explore context");
  });

  it("uses raw descriptionContext when roleId has no factory", () => {
    const config = {
      ...baseConfig,
      partners: [createPartner("unknown-role", "brief", "raw context")],
    };
    const result = createResultDetail(config);
    expect(result.partners[0]!.description).toBe("raw context");
  });

  it("handles multiple partners", () => {
    const config = {
      ...baseConfig,
      partners: [
        createPartner("organizer", "org brief", "org context"),
        createPartner("unknown", "unk brief", "unk context"),
      ],
    };
    const result = createResultDetail(config);
    expect(result.partners).toHaveLength(2);
    // organizer has a factory
    expect(result.partners[0]!.description).toContain("org context");
    expect(result.partners[0]!.description).not.toBe("org context");
    // unknown falls back to raw
    expect(result.partners[1]!.description).toBe("unk context");
  });
});

describe("LEARNING_STRATEGIES", () => {
  it("contains expected strategy keys", () => {
    expect(LEARNING_STRATEGIES.DEEP_READING).toBeDefined();
    expect(LEARNING_STRATEGIES.KNOWLEDGE_STRUCTURE).toBeDefined();
    expect(LEARNING_STRATEGIES.TASK_BREAKDOWN).toBeDefined();
    expect(typeof LEARNING_STRATEGIES.DEEP_READING).toBe("string");
  });
});
